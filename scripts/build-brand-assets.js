/* Rebuild the offline logo bundle from original, locally downloaded brand assets. */
const { readFileSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { createHash } = require('node:crypto');
const directory = resolve(__dirname, '../assets/brands');
const manifest = JSON.parse(readFileSync(resolve(directory, 'manifest.json'), 'utf8'));
function embed(asset) {
  const bytes = readFileSync(resolve(directory, asset.file));
  return { ...asset, sha256: createHash('sha256').update(bytes).digest('hex'), src: `data:${asset.mime};base64,${bytes.toString('base64')}` };
}
const data = { retrieved: manifest.retrieved, brands: manifest.brands.map(embed), partners: manifest.partners.map(embed) };
const code = `/* Generated by scripts/build-brand-assets.js. Original sources: assets/brands/manifest.json. */
(function (root) {
  'use strict';
  const data = ${JSON.stringify(data)};
  const brands = Object.freeze(data.brands.map(Object.freeze));
  const partners = Object.freeze(data.partners.map(Object.freeze));
  const byId = (list, id) => list.find(asset => asset.id === id) || null;
  const api = Object.freeze({ brands, partners, retrieved: data.retrieved,
    getBrand: id => byId(brands, id), getPartner: id => byId(partners, id),
    brandId: id => id === 'none' || byId(brands, id) ? id : 'yamaha',
    partnerId: (id, brand = 'yamaha') => id === 'none' || byId(partners, id) ? id : (brand === 'yamaha' ? 'maw' : 'none')
  });
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.ServiceBrandAssets = api;
})(globalThis);
`;
writeFileSync(resolve(__dirname, '../service-brands.js'), code);
console.log(`Bundled ${data.brands.length} brand logos and ${data.partners.length} partner logo (${Buffer.byteLength(code)} bytes).`);
